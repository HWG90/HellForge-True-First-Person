#!/usr/bin/env bash
# Continuity of the presented eye through the camera helper, on the differential test's fake game memory:
# tests/camera_smooth_test.cpp. Needs g++ and Linux (process_vm_readv); no retail source.
set -euo pipefail
TFP_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TFP_CC="${CC:-cc}"
mkdir -p "$TFP_ROOT/work/tests"
if ! command -v g++ >/dev/null || [ "$(uname -s)" != Linux ]; then echo "Camera smooth: skipped (g++ or Linux not found)"; exit 0; fi
"$TFP_CC" -std=c11 -O1 -ffp-contract=off -Wall -Wextra -Werror -fsanitize=address,undefined -g -I "$TFP_ROOT/src" -c "$TFP_ROOT/src/camera_helper.c" \
  -o "$TFP_ROOT/work/tests/camera_helper_smooth.o"
g++ -std=c++17 -O1 -ffp-contract=off -Wall -Wextra -Werror -fsanitize=address,undefined -g -I "$TFP_ROOT/src" -I "$TFP_ROOT/tests" \
  "$TFP_ROOT/tests/camera_smooth_test.cpp" "$TFP_ROOT/work/tests/camera_helper_smooth.o" -lm -o "$TFP_ROOT/work/tests/camera_smooth_test"
ASAN_OPTIONS=detect_leaks=0 "$TFP_ROOT/work/tests/camera_smooth_test"
