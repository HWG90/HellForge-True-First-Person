FROZEN = "1d0d453"
NAN, INF = float("nan"), float("inf")


def lua(value):
    if value is None: return "nil"
    if isinstance(value, bool): return "true" if value else "false"
    if isinstance(value, float) and value != value: return "(0/0)"
    if isinstance(value, float) and value in (INF, -INF): return "math.huge" if value > 0 else "-math.huge"
    if isinstance(value, (int, float)): return repr(value)
    if isinstance(value, str): return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')
    if isinstance(value, dict): return "{" + ",".join(f"{k}={lua(v)}" for k, v in value.items()) + "}"
    if isinstance(value, (list, tuple)): return "{" + ",".join(lua(v) for v in value) + "}"
    raise TypeError(value)


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("??", "?\\?") + '"'


# ---- quaternions (x, y, z, w) and vectors, only to lay scenes out; the runner rounds to float ----
def axis_angle(axis, angle):
    n = math.sqrt(sum(c * c for c in axis)) or 1.0
    s = math.sin(angle / 2) / n
    return (axis[0] * s, axis[1] * s, axis[2] * s, math.cos(angle / 2))


def qmul(a, b):
    return (a[3] * b[0] + a[0] * b[3] + a[1] * b[2] - a[2] * b[1], a[3] * b[1] - a[0] * b[2] + a[1] * b[3] + a[2] * b[0],
            a[3] * b[2] + a[0] * b[1] - a[1] * b[0] + a[2] * b[3], a[3] * b[3] - a[0] * b[0] - a[1] * b[1] - a[2] * b[2])


def qrot(q, p):
    r = qmul(qmul(q, (p[0], p[1], p[2], 0.0)), (-q[0], -q[1], -q[2], q[3]))
    return (r[0], r[1], r[2])


def qinv(q): return (-q[0], -q[1], -q[2], q[3])
def add(a, b): return (a[0] + b[0], a[1] + b[1], a[2] + b[2])
def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def scale(a, n): return (a[0] * n, a[1] * n, a[2] * n)
def length(a): return math.sqrt(a[0] * a[0] + a[1] * a[1] + a[2] * a[2])
IDENTITY = (0.0, 0.0, 0.0, 1.0)


def random_rotation(rng, most=math.pi):
    return axis_angle((rng.uniform(-1, 1), rng.uniform(-1, 1), rng.uniform(-1, 1) or 1.0), rng.uniform(-most, most))


def pose_edit(unit, node, q, p):
    return ["pose", unit, node, *[float(c) for c in q], *[float(c) for c in p]]


def link_word(mode, parent): return mode + parent * 65536


ORIGIN = 0x1A2B3C4D5E60                                     # arms_common.lua: where unit objects sit, 1 MiB apart


def address(unit): return ORIGIN + unit * 0x100000


def run(runner, retail, runs):
    """runs: [{name, missing, ops}] -> one output line per operation."""
    with tempfile.NamedTemporaryFile("w", suffix=".lua", delete=False) as script:
        for r in runs:
            script.write("{run=%s,missing=%s}\n" % (lua(r["name"]), lua(r.get("missing", []))))
            script.write("".join(lua(o) + "\n" for o in r["ops"]))
    done = subprocess.run(["luajit", str(runner), str(retail), script.name], capture_output=True, text=True)
    Path(script.name).unlink()
    if done.returncode:
        sys.exit(f"{runner.name} failed:\n{done.stdout[-1500:]}\n{done.stderr[-3000:]}")
    lines = done.stdout.split("\n")[:-1]
    total = sum(len(r["ops"]) for r in runs)
    if len(lines) != total:
        sys.exit(f"{len(lines)} results for {total} operations")
    return lines


def frozen_commit(retail):
    commit = subprocess.check_output(["git", "-C", str(retail), "rev-parse", "--short", "HEAD"], text=True).strip()
    if commit != FROZEN:
        sys.exit(f"Retail is at {commit}; this project is frozen at {FROZEN}.")
    return commit


def write_header(out, prefix, title, commit, source, runs, lines):
    """prefix: arm_pieces / grip_hand."""
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    upper = prefix.upper()
    text = [f"/* Generated by tools/retail_ref/gen_{prefix}.py. Do not edit.\n * Retail file: src/first_person/{source.name} at commit {commit}, "
            f"sha256 {digest}.\n * {title}\n"
            " * Each vector is one operation as the runner printed it:\n"
            " *   instance|call|snapshot|active|handles|maths failure|recorded engine calls|maths count,checksum|answer\n"
            " * (`engine`: from this operation on the engine lacks the functions named in the snapshot field.)\n"
            " * The engine calls are what the retail file asked the scripted engine, in order, with every argument and\n"
            " * the answer it got; tests/arms_fx.h hands the same answers to the C and requires the same calls. */",
            f'#define {upper}_VECTOR_COMMIT "{commit}"', f'#define {upper}_VECTOR_SHA256 "{digest}"',
            "#ifndef ARMS_VECTOR_TYPES\n#define ARMS_VECTOR_TYPES\n"
            "typedef struct ArmsRun { const char *name; const char *missing; } ArmsRun;\n"
            "typedef struct ArmsVector { int run; const char *line; } ArmsVector;\n#endif",
            f"static const ArmsRun {prefix}_runs[] = {{"]
    text += ["  {%s,%s}," % (c_string(r["name"]), c_string(" ".join(r.get("missing", [])))) for r in runs]
    text += ["};", f"static const ArmsVector {prefix}_vectors[] = {{"]
    at = 0
    for index, r in enumerate(runs):
        for _ in r["ops"]:
            text.append("  {%d,%s}," % (index, c_string(lines[at])))
            at += 1
    text.append("};")
    (out / f"{prefix}_vectors.h").write_text("\n".join(text) + "\n")
    return digest
