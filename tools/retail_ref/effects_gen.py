#!/usr/bin/env python3
"""Shared by gen_<module>.py of the effects modules: runs tools/retail_ref/run_<module>.lua (the
retail Lua file, unmodified, under LuaJIT against scripted fakes; see effects_common.lua for the
protocol) and writes tests/vectors/<module>_vectors.h for tests/<module>_test.c (tests/effects_fx.h).

  gen_<module>.py --retail "<Goose Gadget Kit folder>" --out tests/vectors
"""
import argparse
import hashlib
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FROZEN = "1d0d453"


def c_bytes(data):
    """A C string literal for arbitrary bytes (three-digit octal escapes, so no escape runs on)."""
    out = []
    for b in data:
        if 32 <= b <= 126 and chr(b) not in '"\\?': out.append(chr(b))
        else: out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def c_double(bits):
    value = struct.unpack(">d", bytes.fromhex(bits))[0]
    if value != value: return "NAN"
    if value in (float("inf"), float("-inf")): return "INFINITY" if value > 0 else "-INFINITY"
    return value.hex()


def c_value(text):
    kind = text[0]
    if kind in "nft": return "{'%s',0,0,0}" % kind
    if kind == "d": return "{'d',%s,0,0}" % c_double(text[1:])
    data = bytes.fromhex(text[1:])
    return "{'s',0,%s,%d}" % (c_bytes(data), len(data))


def generate(module, lua_file, also=()):
    """module: the C module name (dof_fx, vignette, ...); lua_file: the retail file under
    src/first_person/; also: more retail files whose hash the header records."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--retail", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--runner", type=Path, default=HERE / f"run_{module}.lua", help="for the coverage review: a wrapper of the runner")
    args = parser.parse_args()
    commit = subprocess.check_output(["git", "-C", str(args.retail), "rev-parse", "--short", "HEAD"], text=True).strip()
    if commit != FROZEN:
        sys.exit(f"Retail is at {commit}; this project is frozen at {FROZEN}.")
    digest = hashlib.sha256((args.retail / "src/first_person" / lua_file).read_bytes()).hexdigest()
    extra = "".join(f"\n * (with src/first_person/{name}, sha256 {hashlib.sha256((args.retail / 'src/first_person' / name).read_bytes()).hexdigest()})."
                    for name in also)
    done = subprocess.run(["luajit", str(args.runner), str(args.retail)], capture_output=True)
    if done.returncode:
        sys.exit(f"{args.runner.name} failed:\n{done.stdout[-2000:].decode(errors='replace')}\n{done.stderr.decode(errors='replace')}")
    slots, runs, ops, events = [], [], [], []
    for raw in done.stdout.split(b"\n")[:-1]:
        kind, _, rest = raw.partition(b"\t")
        if kind == b"S": slots.append(rest.decode())
        elif kind == b"R": runs.append([rest.decode(), len(ops), 0])
        elif kind == b"O":
            parts = rest.decode().split("\t")
            ops.append([parts[0], parts[1:5], len(events), 0, None])
            runs[-1][2] += 1
        elif kind == b"E":
            at, slot, key, value = rest.decode().split("\t")
            events.append("{%s,W_%s,%d,%s,%s}" % (at, slot, key != "-", c_double(key) if key != "-" else "0", c_value(value)))
            ops[-1][3] += 1
        elif kind == b"X": ops[-1][4] = rest
        else: sys.exit(f"unexpected runner line: {raw[:200]!r}")
    if any(o[4] is None for o in ops): sys.exit("an operation has no result")
    upper = module.upper()
    out = [f"/* Generated by tools/retail_ref/gen_{module}.py. Do not edit.\n * Retail file: src/first_person/{lua_file} at commit {commit}, sha256 {digest}{extra}\n"
           " * Each run starts a fresh module instance and an empty world. Every operation lists the world changes its\n"
           " * scripted fakes see (tests/effects_fx.h) and `expect`: what the retail file returned, its state afterwards\n"
           " * and the ordered trace of the host calls it made. */",
           f'#define {upper}_VECTOR_COMMIT "{commit}"', f'#define {upper}_VECTOR_SHA256 "{digest}"',
           "enum { " + ", ".join("W_" + s for s in slots) + ", W_COUNT };",
           f"static const char *const {module}_slots[] = {{" + ", ".join('"%s"' % s for s in slots) + "};",
           f"static const FxEvent {module}_events[] = {{"]
    out += ["  " + e + "," for e in events] or ["  {0,0,0,0,{'n',0,0,0}},"]
    out += ["};", f"static const FxOp {module}_ops[] = {{"]
    out += ["  {\"%s\",{%s},%d,%d,%s}," % (o[0], ",".join(c_value(a) for a in o[1]), o[2], o[3], c_bytes(o[4])) for o in ops]
    out += ["};", f"static const FxRun {module}_runs[] = {{"]
    out += ["  {\"%s\",%d,%d}," % (r[0], r[1], r[2]) for r in runs]
    out += ["};"]
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / f"{module}_vectors.h").write_text("\n".join(out) + "\n")
    calls = {}
    for o in ops: calls[o[0]] = calls.get(o[0], 0) + 1
    for r in runs: print(f"{r[0]}: {r[2]} operations")
    print(f"{module}: {len(ops)} operations in {len(runs)} runs (" + ", ".join(f"{k} {v}" for k, v in sorted(calls.items())) + ")")
    return 0
