#!/usr/bin/env python3
"""Map build constants between HellForge's build 25480438 and retail 26568081.

The retail kit keeps the record of each of its own moves between builds:
docs/first-person-applied-migration.json (25480438 -> 26088801),
first-person-26251122-migration.json and first-person-26568081-migration.json.
Composed, they give the retail value of every constant the mode had when it
was first written on 25480438; inverted, the value here of a retail constant.
Constants that only appear in the later records were added after the first
move and have no value here yet: they are listed as retail-only.

  build_map.py --retail <kit folder> --write docs/build-25480438/BUILD-DATA-25480438.md
  build_map.py --retail <kit folder> --to-here 0x2e287d0 0x53e888
"""
import argparse
import json
import sys
from pathlib import Path

FILES = ("docs/first-person-applied-migration.json", "docs/first-person-26251122-migration.json",
         "docs/first-person-26568081-migration.json")


def load(retail):
    first, second, third = (json.loads((retail / name).read_text()) for name in FILES)
    def table(record):
        return {int(k, 16): int(v, 16) for k, v in record["constants"].items()}
    a, b, c = table(first), table(second), table(third)
    here_to_retail = {}
    for here, value in a.items():
        value = b.get(value, value)
        here_to_retail[here] = c.get(value, value)
    reached = set(here_to_retail.values())
    # Later constants with no ancestor on 25480438.
    later = {}
    for value in b.values():
        value = c.get(value, value)
        if value not in reached:
            later[value] = 26251122
    for value in c.values():
        if value not in reached and value not in later:
            later[value] = 26568081
    return here_to_retail, later


def retail_to_here(here_to_retail):
    inverse = {}
    clashes = set()
    for here, retail in here_to_retail.items():
        if retail in inverse and inverse[retail] != here:
            clashes.add(retail)
        inverse[retail] = here
    return inverse, clashes


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--retail", type=Path, required=True)
    parser.add_argument("--write", type=Path)
    parser.add_argument("--to-here", nargs="*", default=[])
    args = parser.parse_args()
    here_to_retail, later = load(args.retail)
    inverse, clashes = retail_to_here(here_to_retail)
    status = 0
    for text in args.to_here:
        value = int(text, 16)
        if value in clashes:
            print(f"{value:#x} -> AMBIGUOUS")
            status = 1
        elif value in inverse:
            print(f"{value:#x} -> {inverse[value]:#x}")
        else:
            print(f"{value:#x} -> UNKNOWN ({'added on ' + str(later[value]) if value in later else 'not in the records'})")
            status = 1
    if args.write:
        lines = ["# Build data: 25480438 (HellForge) against 26568081 (retail)", "",
                 "Generated by `tools/build_map.py` from the retail kit's own build-migration records "
                 "(`docs/first-person-applied-migration.json` and the two later ones). Do not edit by hand; "
                 "hand-established values go in the second table of `docs/build-25480438/BUILD-DIFFERENCES.md`.", "",
                 f"## Constants carried since 25480438 ({len(here_to_retail)})", "",
                 "| here (25480438) | retail (26568081) | changed |", "|---|---|---|"]
        for here in sorted(here_to_retail):
            retail = here_to_retail[here]
            note = "ambiguous on the way back" if retail in clashes else ("" if here == retail else "yes")
            lines.append(f"| `{here:#x}` | `{retail:#x}` | {note} |")
        lines += ["", f"## Retail constants with no value here yet ({len(later)})", "",
                  "These appear only in the later records. Most entered the retail mode after it left 25480438; "
                  "some existed here and were first written down when they first changed. Either way the records "
                  "give no value for this build: each one the live path uses has to be found by hand before the "
                  "code that needs it is written.", "",
                  "| retail (26568081) | first seen in the move to |", "|---|---|"]
        for value in sorted(later):
            lines.append(f"| `{value:#x}` | {later[value]} |")
        args.write.write_text("\n".join(lines) + "\n")
    return status


if __name__ == "__main__":
    sys.exit(main())
